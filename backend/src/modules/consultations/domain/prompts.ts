import {
  MED_CARD_EMPTY_SECTION,
  SPECIALTY_NAMES,
  type DoctorSpecialty,
} from '@mediqaz/contracts'

/**
 * Kazakh clinical terms the model has been observed flattening into the wrong
 * Russian concept — e.g. "зев өте қызарған" (the throat is severely
 * hyperemic) came back as "зев ослаблен" ("the throat is weakened"), a
 * different clinical finding, not a looser paraphrase of the same one. Listed
 * here rather than left to the model's general translation, because a wrong
 * substitution reads as confidently correct: nothing about the output signals
 * that a term was guessed rather than known.
 */
export const KAZAKH_MEDICAL_GLOSSARY: ReadonlyArray<readonly [string, string]> = [
  ['қызарған', 'гиперемированный / покрасневший'],
  ['ісінген', 'отёчный / увеличенный'],
  ['ауырсыну', 'боль / болезненность'],
  ['жөтел құрғақ', 'сухой кашель'],
  ['жөтел дымқыл', 'влажный кашель / кашель с мокротой'],
  ['ентігу', 'одышка'],
  ['қақырық', 'мокрота'],
  ['шырышты бөліну', 'выделения / секреция'],
  ['дем алу', 'дыхание'],
  ['бас ауруы', 'головная боль'],
  ['бас айналу', 'головокружение'],
  ['дене қызуы', 'температура тела'],
  ['жүрек айну', 'тошнота'],
  ['іш өту', 'диарея'],
  ['несеп / зәр', 'моча'],
  ['буын', 'сустав'],
  ['бел ауруы', 'боль в пояснице'],
  ['кеуде', 'грудная клетка'],
  ['бадамша без', 'миндалины'],
  ['лимфа түйіні', 'лимфатический узел'],
  ['қақырық түсу', 'отхождение мокроты'],
  ['тамақ ауруы', 'боль в горле'],
  ['мұрын бітелуі', 'заложенность носа'],
  ['тұмау', 'насморк / простуда'],
]

function formatKazakhGlossary() {
  return KAZAKH_MEDICAL_GLOSSARY.map(([kk, ru]) => `${kk} → ${ru}`).join('\n')
}

/**
 * The med-card prompt is a product rule, not provider configuration: it decides
 * which sections exist, that nothing may be invented, and that a diagnosis
 * always carries an ICD-10 code. It lives in the domain so the client cannot
 * weaken it and so switching model providers does not rewrite it.
 */
export function buildMedCardSystemPrompt({
  specialty,
  customInstructions = '',
  voiceCommands = [],
}: {
  specialty: DoctorSpecialty
  customInstructions?: string
  voiceCommands?: string[]
}) {
  const specialtyName = SPECIALTY_NAMES[specialty]

  const custom = customInstructions
    ? `ПЕРСОНАЛЬНЫЕ ИНСТРУКЦИИ ВРАЧА (АБСОЛЮТНЫЙ ПРИОРИТЕТ):\n${customInstructions}\n`
    : ''

  const voice = voiceCommands.length
    ? `ГОЛОСОВЫЕ КОМАНДЫ ВРАЧА (ПРИОРИТЕТ ВЫШЕ ИНСТРУКЦИЙ):\n${voiceCommands
        .map((command) => `- ${command}`)
        .join('\n')}\n`
    : ''

  return `Ты — опытный врач-ассистент (специальность: ${specialtyName}) в системе здравоохранения Казахстана.

${custom}${voice}
ПРАВИЛА:
1. Извлекай информацию ТОЛЬКО из транскрипции. НИКОГДА не придумывай данные.
2. ОПРЕДЕЛИ ТИП ПРИЁМА по контексту диалога:
   - Явное указание на первый визит ("впервые", "первый раз", "никогда не был", "алғаш рет") — верни "Первичный".
   - Явное указание на прошлые визиты ("повторно", "опять пришёл", "в прошлый раз", упоминание прежних анализов или назначений) — верни "Повторный".
   - Нет явных указаний — верни null. Не угадывай.
3. Если данных для секции нет — напиши точно: "${MED_CARD_EMPTY_SECTION}".
4. Для каждой секции укажи ТОЧНУЮ дословную цитату из транскрипции в поле "цитата".
5. ДИАГНОЗ ("диагноз_врача") — ТОЛЬКО то, что врач произнёс явно словами
   и/или назвал код МКБ-10. Если врач не произнёс диагноз явно — "текст":
   null и "мкб10": null.
   Тебе ЗАПРЕЩЕНО выдвигать диагностические гипотезы. Не делай собственных
   клинических выводов и не предполагай диагноз на основе симптомов,
   жалоб или объективных данных — ни в каком поле, ни в каком виде. Врач,
   который не назвал диагноз, его не поставил: не ставь диагноз за него.
6. НАЗНАЧЕНИЯ — каждый препарат отдельным объектом со своими полями: препарат,
   доза, кратность, длительность, условие_приема, цитата.
   Если врач указал условие приёма препарата (например "только если температура
   выше 38.5" или "если боль не пройдёт за два дня") — зафиксируй это условие
   ТОЧНО, своими словами врача. НЕ УПРОЩАЙ и не отбрасывай условие приёма.
   Потеря условия меняет назначение: "Парацетамол при температуре выше 38.5" и
   "Парацетамол" — это разные назначения, а не одно, изложенное короче.
   Если для поля (доза, кратность, длительность, условие_приема) значение не
   прозвучало явно — верни null для этого поля. Не придумывай значение и не
   подставляй пустую строку вместо null.
7. КРАСНЫЕ_ФЛАГИ (когда срочно обращаться за помощью или вызывать скорую) —
   обязательное поле. Если врач явно назвал такие признаки — зафиксируй их
   дословно в "текст". Если врач НЕ называл таких признаков — верни
   "текст": null. НЕ придумывай красные флаги от себя, даже если они кажутся
   уместными для этого диагноза: источник — только то, что сказал врач.
8. Язык — русский. Медицинские термины по стандарту РК. При переводе казахских
   медицинских терминов используй глоссарий ниже. Не заменяй специфические
   клинические термины общими словами — "қызарған" это "гиперемированный/
   покрасневший", а не "воспалённый" или "ослабленный".
9. Верни ТОЛЬКО JSON, без пояснений и markdown.

ГЛОССАРИЙ КАЗАХСКИХ МЕДИЦИНСКИХ ТЕРМИНОВ:
${formatKazakhGlossary()}`
}

export function buildMedCardUserPrompt(transcript: string) {
  return `ТРАНСКРИПЦИЯ ПРИЁМА:
${transcript}

Верни строго JSON:
{
  "тип_приема":       "Первичный или Повторный",
  "жалобы":           { "текст": "...", "цитата": "точные слова из транскрипции" },
  "анамнез":          { "текст": "...", "цитата": "..." },
  "объективно":       { "текст": "...", "цитата": "..." },
  "диагноз_врача":    { "текст": "... или null, если врач не назвал диагноз явно", "мкб10": "код или null, только если врач его назвал", "цитата": "..." },
  "назначения": {
    "items": [
      {
        "препарат": "...",
        "доза": "... или null, если не прозвучало",
        "кратность": "... или null",
        "длительность": "... или null",
        "условие_приема": "... или null — например 'только при температуре выше 38.5'",
        "цитата": "точные слова из транскрипции про этот препарат"
      }
    ]
  },
  "красные_флаги":    { "текст": "... или null, если врач не называл таких признаков", "цитата": "..." },
  "рекомендации":     { "текст": "...", "цитата": "..." },
  "следующий_прием":  { "текст": "...", "цитата": "..." }
}`
}

/** Prompt for the "ask about this consultation" mode. */
export function buildQuestionPrompt({
  specialty,
  transcript,
  question,
}: {
  specialty: DoctorSpecialty
  transcript: string
  question: string
}) {
  const specialtyName = SPECIALTY_NAMES[specialty]

  return {
    system: `Ты — опытный врач-ассистент (${specialtyName}).
Отвечай на вопросы врача, основываясь ТОЛЬКО на предоставленной транскрипции приёма.
Если ответа нет в тексте — так и скажи.
Если ответ найден, включи в конец ответа точную цитату в кавычках для подтверждения.`,
    user: `ТРАНСКРИПЦИЯ ПРИЁМА:\n${transcript}\n\nВОПРОС ВРАЧА: ${question}`,
  }
}
